// Узел потока: стадия и её имя. Узла нет в перечне: шаг честным именем стадии
// не называем, он уходит в «Другие шаги».
const NODE_STAGE = new Map<string, { key: RunStage; label: string }>(
  RUN_STAGES.flatMap((stage) => stage.nodes.map((node) => [node, { key: stage.key, label: stage.label }])),
);

export function stageOfNode(node: string | null | undefined): { key: RunStage; label: string } | null {
  if (!node) return null;
  return NODE_STAGE.get(node) ?? NODE_STAGE.get(node.toLowerCase()) ?? null;
}

/** Роль узла контура словами стадии: «Reasoner» читается как «Сборка ответа». */
function contourRole(key: string | null | undefined): string | null {
  return stageOfNode(key)?.label ?? null;
}

/** Стадия строчным регистром для середины фразы: «сборка ответа». */
function stageWord(key: RunStage): string {
  const label = RUN_STAGES.find((stage) => stage.key === key)?.label ?? 'обработка ответа';
  return label.charAt(0).toLowerCase() + label.slice(1);
}

