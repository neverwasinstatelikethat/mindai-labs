// ── Стадии сборки ответа: один перечень на весь экран ───────────────────────
// Ответ собирается в пять стадий, и человек читает их как «что сделали». Имена
// узлов контура (`planning_agent`, `critic`, …) остаются ключами: по ним приходят
// события потока, на экран они не попадают. Больше одного словаря про один
// процесс нет: `CONTOUR_ROLES` и `RUN_STAGES` здесь объединены, роль узла
// читается из стадии.
