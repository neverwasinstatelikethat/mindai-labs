/** Русская причина неполного ответа: известная строка — по словарю, незнакомая —
 *  как пришла, но со служебными именами контура, заменёнными на русские. */
export function degradationOf(reason: string): string {
  const text = reason.trim();
  for (const { pattern, say } of DEGRADATION_RULES) {
    const match = pattern.exec(text);
    if (match) return say(match.slice(1).map((part) => part ?? ''));
  }
  return CONTOUR_WORDS.reduce(
    (value, [pattern, word]) => value.replace(pattern, word),
    text,
  );
}

