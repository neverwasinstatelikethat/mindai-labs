/** Имя для экрана: сначала словарь, затем понятная заглушка. */
export function findingsTerm(
  map: Record<string, string>,
  key: string | null | undefined,
  names: { absent: string; unknown: string },
): { label: string } {
  if (!key) return { label: names.absent };
  const label = knownTerm(map, key);
  return { label: label ?? names.unknown };
}

/** Регистр задаёт экран: имя связи в словаре строчное, как на карте, а в
 *  заголовке или жирной подписи оно начинается с большой буквы. */
export function headingTerm(value: string): string {
  if (!value) return value;
  return value.charAt(0).toUpperCase() + value.slice(1);
}

/** Пределы полосы: они посчитаны по загруженной части списка, и подпись говорит то
 *  же самое, а не называет их «корпусом». Единица стоит там, где её читают рядом с
 *  числами, а число значений не склеивается с подписью в одну строку. */
export function findingsScaleSpread(unit: string, values: number): string {
  const label = unitLabel(unit);
  const inUnit = label.label ? ` в ${label.label}` : '';
  const asIs = label.label && !label.known ? `; ${UNIT_AS_IN_SOURCE}` : '';
  return `Минимум и максимум${inUnit} среди загруженных находок, всего ${num(values)} значений${asIs}`;
}

/** Почему у наблюдения нет полосы: предела нет у самого показателя, у строки нет
 *  приведённого числа либо значение встречалось один раз. */
export function findingsScaleGapNote(reason: 'absent' | 'noValue' | 'single'): string {
  if (reason === 'single') {
    return 'Среди загруженных находок этот показатель встречался один раз, сравнивать значение не с чем.';
  }
  if (reason === 'noValue') {
    return 'У этого наблюдения нет приведённого числа, поэтому пределов у полосы нет.';
  }
  return 'Среди загруженных находок у этого показателя нет приведённых чисел, пределы не построить.';
}
