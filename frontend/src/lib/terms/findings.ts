/** Чем пустой список без показанного отличается от пустого корпуса: подтверждённый
 *  ноль, отсутствие показания и непрогруженные строки называются по-разному, и ни
 *  один из этих случаев не назван пустым корпусом. */
export function findingsNotLoadedBody(total: number | null): string {
  return total === null
    ? 'Сервис не вернул ни одной находки и не назвал их число.'
    : 'Гипотезы есть, но список пока не загрузился.';
}

/** Счётчик над списком: «Показано 25 из 6 897 находок», при неизвестном полном
 *  числе только числитель. `qualifier` сужает знаменатель до той области, на
 *  которую смотрит человек. */
export function findingsShownOf(shown: number, total: number | null, qualifier = ''): string {
  if (total === 0) return `Находок нет${qualifier}`;
  const shownText = countOf(shown, 'находка', 'находки', 'находок');
  if (total === null) return `Показано ${shownText}${qualifier}`;
  if (total <= shown)
    return shown === 1
      ? `Показана 1 находка${qualifier}`
      : `Показаны все ${shownText}${qualifier}`;
  return `Показано ${num(shown)} из ${countOf(total, 'находка', 'находки', 'находок')}${qualifier}`;
}

