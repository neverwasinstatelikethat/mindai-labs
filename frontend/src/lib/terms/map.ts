/**
 * Имя области — только человеческое. Сервер подписывает области по-русски
 * («Водоподготовка», «Сообщество 1», «База знаний»); значение, целиком
 * записанное латиницей, цифрами и разделителями ключей, — сырой ключ из
 * хранилища, и именем области он не становится.
 */
const RAW_AREA_KEY = /^[A-Za-z0-9_\-.:]+$/;

export function mapAreaName(raw: unknown): string {
  if (typeof raw !== 'string') return MAP_UNNAMED_AREA;
  const value = raw.trim();
  if (value === '' || RAW_AREA_KEY.test(value)) return MAP_UNNAMED_AREA;
  return value;
}

