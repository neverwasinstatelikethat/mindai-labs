/** Сколько строк поиска показано и сколько найдено всего. Одна строка требует
 *  женского рода («показана 1 запись»), иначе фраза ломается на первом результате. */
export function mapSearchShownOf(shown: number, total: number, query: string): string {
  if (total === 1) return `Показана ${countOf(total, 'запись', 'записи', 'записей')} по «${query}».`;
  if (shown >= total) {
    return `Показаны все ${countOf(total, 'запись', 'записи', 'записей')} по «${query}».`;
  }
  return `Показано ${shown} из ${total} ${countOf(total, 'запись', 'записи', 'записей')}.`;
}

/** Ничего не нашлось: это не пустая карта, а отсутствие совпадения по названию. */
export function mapSearchEmptyBody(query: string): string {
  return `Записи с «${query}» в названии на загруженной карте нет.`;
}

