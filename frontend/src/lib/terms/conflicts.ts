/** Одна строка пробела: что именно не даёт сверить числа. */
export function gapBody(kind: GapKind, topic: string, findings: string, units: string[]): string {
  if (kind === 'pair') {
    return `По теме «${topic}» одно оспоренное утверждение: сверять число не с чем.`;
  }
  if (kind === 'unit') {
    const named = units.length > 0 ? ` Названы ${units.join(', ')}.` : '';
    return `В теме «${topic}» ${findings}, но показатель не назван дважды в одинаковых единицах.${named}`;
  }
  if (kind === 'value') {
    return 'В утверждении нет числа: расхождение видно только по формулировке.';
  }
  return 'У утверждения нет доказательств: сверить его по листу или ячейкам нельзя.';
}

/**
 * Одна строка счётчика пробелов: сколько показано, из чего посчитано и какое
 * окно загружено. Знаменатели стоят в той же фразе, методика — в «i»: раньше
 * служебный счётчик и человеческое предложение склеивались в одну строку.
 */
export function gapsCount(
  shown: number,
  counted: number,
  loaded: number,
  corpusTotal: number | null,
  windowSize: number,
): string {
  const head =
    counted === 0
      ? 'Пробелов нет'
      : shown < counted
        ? `Пробелов: ${shown} из ${counted}`
        : `Пробелов: все ${counted}`;
  const rest =
    corpusTotal === null
      ? `${loaded} оспоренных утверждений загружено, полного числа сервис не назвал`
      : `${loaded} из ${corpusTotal} оспоренных утверждений`;
  return `${head}; знаменатель — загруженное окно (${windowSize}): ${rest}.`;
}

