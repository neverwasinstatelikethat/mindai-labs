/** Сколько утверждений без расхождений, когда список пуст и нуль подтверждён. */
export function noDivergenceBody(claims: number | null): string {
  if (claims === null) {
    return 'Ни одна пара утверждений не помечена оспоренной. Проверьте отбор и прочитайте снова.';
  }
  const corpus = countOf(claims, 'утверждение', 'утверждения', 'утверждений');
  return `В корпусе ${corpus}, и ни одно не оспорено: расхождение появится со вторым документом по показателю.`;
}

/**
 * Сколько пробелов видно и по какому окну они посчитаны: знаменатель стоит в
 * той же строке, что и числитель, а не в отдельном пояснении.
 */
export function gapsCounter(
  shown: number,
  computed: number,
  windowSize: number,
  total: number | null,
): string {
  const windowPhrase =
    total === null
      ? `${windowSize} оспоренных утверждений загруженного окна`
      : `${windowSize} оспоренных утверждений из ${total}`;
  return shown < computed
    ? `Пробелов: ${shown} из ${computed}, окно счёта: ${windowPhrase}`
    : `Пробелов: ${computed}, окно счёта: ${windowPhrase}`;
}

