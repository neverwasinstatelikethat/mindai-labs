/** Хвост фразы с названным знаменателем: доля всегда при своём основании. */
export function deltaBasis(denominator: number, unit: string): string {
  const suffix = unit ? ` ${unit}` : '';
  return `от его значения ${num(denominator)}${suffix}`;
}

/**
 * Фраза сравнения от главного источника. Знаменатель назван в той же фразе,
 * поэтому смена главного источника меняет и число, и его основание — молча
 * другой знаменатель не подставляется.
 */
export function deltaPhrase(outcome: DeltaOutcome, unit: string): { lead: string; value: string | null; basis: string } {
  if (!outcome.ok) {
    const lead =
      outcome.miss === 'zero'
        ? DELTA_WORDS.zero
        : outcome.miss === 'negative'
          ? DELTA_WORDS.negative
          : DELTA_WORDS.absent;
    return { lead, value: null, basis: '' };
  }
  const { ratio, denominator } = outcome.delta;
  if (ratio === 0) return { lead: DELTA_WORDS.equal, value: null, basis: '' };
  return {
    lead: ratio > 0 ? DELTA_WORDS.more : DELTA_WORDS.less,
    value: pct(Math.abs(ratio)),
    basis: deltaBasis(denominator, unit),
  };
}

