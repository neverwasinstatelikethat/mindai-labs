// Глубина поиска по-русски и без служебного «скачок».
export function hopsText(hops: number | null | undefined): string {
  if (hops == null) return 'не названа';
  return `${hops} ${plural(hops, 'шаг', 'шага', 'шагов')} от вопроса`;
}

// Ссылки тезиса на фрагменты: одна формулировка на весь экран (шкала, карточка
// тезиса, разбор в шторке). Число склоняется здесь же, чтобы подпись не
// печаталась дважды.
export function linksToText(count: number): string {
  return `${countOf(count, 'ссылка', 'ссылки', 'ссылок')} на фрагменты`;
}

