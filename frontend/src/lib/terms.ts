// ── Имена ключей корпуса (compare, feedback) ──────────────────────────────
// Реальный корпус печатает то, что выдала модель: наряду с «отторжение солей»
// в заголовке столбца оказывается `energy_ratio`. Имя берётся от сервера; если
// сервер прислал служебный ключ, которого словарь не знает, экран ставит
// заглушку, а сырое имя уходит под «Служебные данные».

export const TERM_PLACEHOLDER: Record<'subject' | 'property', string> = {
  subject: 'технология без имени',
  property: 'показатель без имени',
};

// Служебное имя онтологии: латиница с подчёркиваниями или дефисами. Всё
// остальное (кириллица, пробелы) человекочитаемо само по себе.
const SERVICE_KEY_PATTERN = /^[A-Za-z][A-Za-z0-9]*(?:[_-][A-Za-z0-9]+)*$/;

export function isServiceKey(key: string): boolean {
  return SERVICE_KEY_PATTERN.test(key.trim());
}

/** Имена всех ключов списка одним прогоном, чтобы заглушки не повторялись:
 *  когда безымянных показателей несколько, они получают номера. */
export function termLabelsOf(
  keys: readonly string[],
  map: Record<string, string>,
  kind: 'subject' | 'property',
): Record<string, string> {
  const nameOf = (key: string): string | null => {
    const known = map[key];
    if (known) return known;
    const trimmed = key.trim();
    if (!trimmed || isServiceKey(trimmed)) return null;
    // Сервер прислал человеческую строку: показываем её как есть.
    return trimmed;
  };
  const unnamed = keys.filter((key) => nameOf(key) === null);
  const needNumber = unnamed.length > 1;
  const labels: Record<string, string> = {};
  unnamed.forEach((key, index) => {
    const base = TERM_PLACEHOLDER[kind];
    labels[key] = needNumber ? `${base} ${index + 1}` : base;
  });
  for (const key of keys) {
    const name = nameOf(key);
    if (name !== null) labels[key] = name;
  }
  return labels;
}

/** Сырые ключи, заменённые заглушкой: пары «имя на экране: служебное имя» для
 *  раскрытия «Служебные данные». */
export function serviceKeysOf(
  keys: readonly string[],
  map: Record<string, string>,
  kind: 'subject' | 'property',
): { label: string; key: string }[] {
  const labels = termLabelsOf(keys, map, kind);
  return keys
    .filter((key) => !map[key] && isServiceKey(key.trim()))
    .map((key) => ({ label: labels[key], key }));
}

