// переводить то, что нельзя назвать, интерфейс не вправе.
const TRACE_PHRASES: { pattern: RegExp; say: (parts: string[]) => string }[] = [
  {
    pattern: /^Intent=([a-z_]+), план из (\d+) действий$/i,
    say: ([intent, count]) =>
      `вопрос прочитан как «${termOf(INTENT_LABELS, intent)}» · план: ${countOf(
        Number(count),
        'действие',
        'действия',
        'действий',
      )}`,
  },
  {
    pattern: /^План из (\d+) действий: назначение запроса модель не указала$/i,
    say: ([count]) =>
      `план: ${countOf(Number(count), 'действие', 'действия', 'действий')} · назначение запроса не указано`,
  },
  {
    pattern: /^(\d+) actions → (\d+) findings, (\d+) конфликтов, (\d+) пробелов$/i,
    say: ([actions, findings, conflicts, gaps]) =>
      [
        countOf(Number(actions), 'действие', 'действия', 'действий'),
        countOf(Number(findings), 'утверждение', 'утверждения', 'утверждений'),
        countOf(Number(conflicts), 'расхождение', 'расхождения', 'расхождений'),
        countOf(Number(gaps), 'пробел', 'пробела', 'пробелов'),
      ].join(' · '),
  },
  {
    pattern: /^Перепланировано: (\d+) actions$/i,
    say: ([count]) => `план обновлён: ${countOf(Number(count), 'действие', 'действия', 'действий')}`,
  },
  {
    pattern: /^Решение: (continue_tools|reason)(?:; пробелы: (\d+))?$/i,
    say: ([decision, missing]) =>
      RUN_DECISIONS[decision.toLowerCase()] +
      (missing ? ` · не хватает подтверждений: ${missing}` : ''),
  },
  {
    pattern: /^Собран answer на подтверждённых findings$/i,
    say: () => 'ответ собран по подтверждённым утверждениям',
  },
  { pattern: /^Critic одобрил ответ$/i, say: () => 'проверка ответа пройдена' },
  {
    pattern: /^Ревизия ответа по замечаниям Critic$/i,
    say: () => 'ответ пересобран по замечаниям проверки',
  },
  {
    pattern: /^Деградированный ответ: ([\s\S]+)$/i,
    say: ([reason]) => `ответ неполный: ${degradationOf(reason)}`,
  },
  { pattern: /^Ответ собран$/i, say: () => 'ответ собран' },
];

// Незнакомые строки чинятся по частям: служебные имена, перечни идентификаторов
// и классы python-ошибок не должны попадать в текст для аналитика.
const TRACE_FIXES: [RegExp, (...parts: string[]) => string][] = [
  [
    /неизвестные finding ids:\s*\[[^\]]*\]/gi,
    () => 'утверждения вне собранного доказательства',
  ],
  [/числовая fidelity не выдержана/gi, () => 'числа не подтверждены цитатами'],
  [/\bfinding ids?\b/gi, () => 'идентификаторы утверждений'],
  // Идентификатор записи в середине предложения аналитику не о чём говорит.
  [
    /\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b/gi,
    () => 'утверждение',
  ],
  [
    /узел ([a-z_0-9]+) завершился ошибкой(?:\s*\([^)]*\))?/gi,
    (_all: string, node: string) => `${contourRole(node) ?? 'шаг обработки'}: сбой`,
  ],
  [/^Узел ([a-z_0-9]+):/i, (_all: string, node: string) => `${contourRole(node) ?? 'Ответ'}:`],
];

/** Русский текст шага или замечания: известный шаблон — по словарю, незнакомый
 *  — с заменой служебных имён. Пустоты не бывает: без перевода строка остаётся. */
export function tracePhraseOf(text: string): string {
  const source = text.trim();
  for (const { pattern, say } of TRACE_PHRASES) {
    const match = pattern.exec(source);
    if (match) return say(match.slice(1).map((part) => part ?? ''));
  }
  return TRACE_FIXES.reduce(
    (value, [pattern, replacement]) => value.replace(pattern, replacement),
    humanizeContour(source),
  );
}
