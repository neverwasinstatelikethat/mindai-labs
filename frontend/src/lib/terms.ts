/**
 * Почему спор пока нельзя проверить числом. `findings` — уже посчитанное
 * экраном «N утверждений»: согласование числительных остаётся у `format.ts`,
 * словарь даёт формулировку.
 */
export function gapBody(kind: ConflictGapKind, topic: string, findings: string): string {
  if (kind === 'pair') {
    return `По теме «${topic}» в корпусе только одно оспоренное утверждение: сверять не с чем, спор остаётся неподтверждённым.`;
  }
  if (kind === 'scale') {
    return `В теме «${topic}» ${findings}, но ни один показатель не назван дважды в одинаковых единицах: сравнивать числа нечем.`;
  }
  if (kind === 'value') {
    return 'В находке нет числа: расхождение читается только по формулировке и по месту в источнике, проверить его величиной нельзя.';
  }
  return 'У утверждения нет доказательств: проверить его по странице, листу или диапазону ячеек нельзя.';
}

