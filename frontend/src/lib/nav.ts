/**
 * Название раздела по адресу — для экранов, которые ссылаются на разделы
 * (страница ошибки, пустые состояния, перекрёстные кнопки). Берётся из того же
 * списка, что и навигация, чтобы ошибка не звала раздел словом, которого в
 * полосе нет.
 *
 * Старые адреса разделов тоже переводятся в имя: ссылка, которая пережила
 * переезд, не имеет права показывать человеку путь вместо названия.
 */
const LEGACY_LABELS: Record<string, string> = {
  '/compare': '/numbers',
  '/conflicts': '/numbers',
  '/resolution': '/findings',
  '/dashboard': '/account',
  '/feedback': '/numbers',
};

export function navLabel(href: string): string {
  const target = LEGACY_LABELS[href] ?? href;
  const link = NAV_LINKS.find((item) => item.href === target);
  return link?.label ?? target;
}
