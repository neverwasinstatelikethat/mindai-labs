"""Совместимый no-op для прежней пересборки встроенного графа.

StormIdea не создаёт демонстрационные утверждения при preload: знания графа
должны происходить из материалов конкретного рабочего пространства. Функция
сохраняет старый внутренний вызов для локальных сценариев, но не меняет граф.
"""

from __future__ import annotations


def rebuild_semantic_graph(_driver: object) -> dict[str, int]:
    """Ничего не записывает и возвращает совместимые счётчики нулевых изменений."""
    return {
        "nodes_created": 0,
        "edges_created": 0,
        "claims_created": 0,
    }
